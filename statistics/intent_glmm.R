# Frequentist crossed random-intercept logistic model, not Bayesian substitution.
# Rscript statistics/intent_glmm.R predictions.csv output_directory
args <- commandArgs(trailingOnly=TRUE)
if(length(args)!=2) stop('Expected input CSV and output directory')
if(!requireNamespace('lme4',quietly=TRUE) || !requireNamespace('emmeans',quietly=TRUE))
  stop('Install lme4 and emmeans first')
d <- read.csv(args[1], stringsAsFactors=FALSE, fileEncoding='UTF-8')
required <- c('model','seed','sample_id','correct')
if(!all(required %in% names(d))) stop('Missing required columns')
if(anyNA(d[required]) || !all(d$correct %in% c(0,1))) stop('Invalid/missing binary outcome')
if(anyDuplicated(d[c('model','seed','sample_id')])) stop('Duplicate paired cell')
d$model <- factor(d$model);d$seed <- factor(d$seed);d$sample_id <- factor(d$sample_id)
if(any(table(d$model,d$seed,d$sample_id)!=1)) stop('Incomplete paired grid')
if(nlevels(d$seed)<2 || nlevels(d$model)<2) stop('Insufficient levels')
dir.create(args[2],recursive=TRUE,showWarnings=FALSE)
control <- lme4::glmerControl(optimizer='bobyqa',optCtrl=list(maxfun=200000))
null <- lme4::glmer(correct ~ 1+(1|seed)+(1|sample_id), data=d, family=binomial,control=control)
full <- lme4::glmer(correct ~ model+(1|seed)+(1|sample_id), data=d, family=binomial,control=control)
messages <- c(null@optinfo$conv$lme4$messages, full@optinfo$conv$lme4$messages)
diagnostics <- list(convergence_messages=messages, singular_null=lme4::isSingular(null),
                    singular_full=lme4::isSingular(full), seed_levels=nlevels(d$seed))
capture.output(diagnostics,file=file.path(args[2],'diagnostics.txt'))
capture.output(sessionInfo(),file=file.path(args[2],'sessionInfo.txt'))
if(length(messages)>0 || diagnostics$singular_null || diagnostics$singular_full)
  stop('Convergence/singularity problem; inspect diagnostics rather than interpreting p-values')
write.csv(as.data.frame(anova(null,full,test='Chisq')),file.path(args[2],'lrt.csv'))
emm <- emmeans::emmeans(full,~model)
write.csv(as.data.frame(summary(emm,type='response')),file.path(args[2],'estimated_probabilities.csv'),row.names=FALSE)
write.csv(as.data.frame(summary(emmeans::contrast(emm,'pairwise',adjust='holm'),infer=TRUE)),
          file.path(args[2],'pairwise_holm.csv'),row.names=FALSE)
saveRDS(full,file.path(args[2],'full_model.rds'))
